-- Maps to entity: Vote  (requires @Enumerated(EnumType.STRING) on voteType)
CREATE TABLE vote (
    vote_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vote_type VARCHAR(20) NOT NULL,
    post_id   BIGINT      NOT NULL,
    user_id   BIGINT,

    CONSTRAINT ck_vote_type  CHECK (vote_type IN ('UPVOTE', 'DOWNVOTE')),
    CONSTRAINT fk_vote_post  FOREIGN KEY (post_id) REFERENCES post (post_id) ON DELETE CASCADE,
    CONSTRAINT fk_vote_user  FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT uq_vote_user_post UNIQUE (user_id, post_id)
);

CREATE INDEX idx_vote_post_id ON vote (post_id);
