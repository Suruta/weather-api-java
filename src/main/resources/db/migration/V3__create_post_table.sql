-- Maps to entity: Post
CREATE TABLE post (
    post_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_name    VARCHAR(255) NOT NULL,
    url          VARCHAR(255),
    description  TEXT,
    vote_count   INTEGER      NOT NULL DEFAULT 0,
    created_date TIMESTAMPTZ,
    user_id      BIGINT,
    subreddit_id BIGINT,

    CONSTRAINT fk_post_user      FOREIGN KEY (user_id)      REFERENCES users (user_id),
    CONSTRAINT fk_post_subreddit FOREIGN KEY (subreddit_id) REFERENCES subreddit (id)
);

CREATE INDEX idx_post_user_id      ON post (user_id);
CREATE INDEX idx_post_subreddit_id ON post (subreddit_id);
